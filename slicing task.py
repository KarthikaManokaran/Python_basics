##Reverse a string using slicing

Fruit = "Apple"
Rev = Fruit[::-1]
print(Rev)
##-------------------------------------------------------------
##Extract even index characters

name = "karthika"
even_index= name[::2]
print(even_index)

##-------------------------------------------------------------
##Extract odd index characters

name = "AdeeshaAshok"
odd_index = name[1::2]
print(odd_index)

##---------------------------------------------------------------
##Get last 3 elements of list

names = ["karthi","Adee","Aara","Ashok","ARN"]
